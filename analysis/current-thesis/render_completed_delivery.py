"""Standalone Figure 4.4 renderer for the current thesis.
Plotting block is preserved from implement_chapter4.py (27 September 2026).
The input is delivery_shortfall_280_runs.csv generated by the descriptive supplement.
"""
from pathlib import Path
import argparse, hashlib
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D

def build(carrier, output):
    carrier=Path(carrier)
    ROOT=Path(output); ROOT.mkdir(parents=True,exist_ok=True)
    df=pd.read_csv(carrier)
    order=['01_apache_modwsgi','02_nginx_uwsgi','03_django_gunicorn','07_iis_waitress','04_aca','05_koyeb','06_flyio']
    labels=['Apache + mod_wsgi','Nginx + uWSGI','Gunicorn','IIS + Waitress','Azure Container Apps','Koyeb','Fly.io']
    ss=['A_browse','B_mixed','C_checkout','D_burst']
    titles=['A  Browse','B  Mixed','C  Cart-path GET','D  Burst']
    delivery=100*df.k6_iterations/df.planned_starts
    shortfall=100*np.maximum(df.planned_starts-df.k6_iterations,0)/df.planned_starts
    assert len(df)==280 and (shortfall>=5).sum()==10 and (shortfall>1).sum()==28
    assert np.allclose(shortfall,df.shortfall_pct)
    plt.rcParams.update({'font.family':'Nimbus Roman','font.size':10,'axes.titlesize':12,'axes.labelsize':10,'pdf.fonttype':42})
    fig,axs=plt.subplots(4,1,figsize=(6.25,7.15),sharex=True)
    for ax,s,title in zip(axs,ss,titles):
        ax.axvline(100,color='#65717b',ls='--',lw=.8,zorder=0)
        ax.axvline(95,color='#af9588',ls=':',lw=.8,zorder=0)
        for j,platform in enumerate(order):
            d=df[(df.platform==platform)&(df.scenario==s)].sort_values('run_id');assert len(d)==10
            x=100*d.k6_iterations.to_numpy()/d.planned_starts.to_numpy()
            y=j+np.linspace(-.25,.25,10);flag=d.shortfall_pct.to_numpy()>=5
            if j%2==0:ax.axhspan(j-.47,j+.47,color='#f2f5f7',zorder=0)
            ax.scatter(x[~flag],y[~flag],s=13,c='#316a84',alpha=.90,edgecolor='white',linewidth=.25,zorder=3)
            ax.scatter(x[flag],y[flag],s=23,c='#b34420',marker='x',linewidths=1.1,zorder=4)
            ax.scatter([np.median(x)],[j],s=70,c='#14232d',marker='|',linewidths=1.7,zorder=5)
            if flag.any():ax.text(49,j+.28,f'{int(flag.sum())}/10 with ≥5% shortfall',fontsize=10,color='#903d20',va='center')
        ax.set_title(title,loc='left',fontweight='bold',pad=5)
        ax.set_xlim(43,102);ax.set_ylim(6.6,-.6)
        ax.set_xticks([50,60,70,80,90,100]);ax.set_yticks(range(7),labels)
        ax.tick_params(axis='y',length=0);ax.tick_params(axis='x',length=2,labelsize=10)
        ax.grid(axis='x',color='#e1e6e9',linewidth=.5,zorder=0)
        for side in ['top','right','left']:ax.spines[side].set_visible(False)
        ax.spines['bottom'].set_color('#a4aeb5')
    axs[-1].set_xlabel('Completed iterations / planned starts (%)')
    handles=[Line2D([],[],color='#316a84',marker='o',ls='',markersize=4,label='Run: shortfall <5%'),Line2D([],[],color='#b34420',marker='x',ls='',markersize=5,label='Run: shortfall ≥5%'),Line2D([],[],color='#14232d',marker='|',ls='',markersize=9,markeredgewidth=1.7,label='Cell median')]
    fig.legend(handles=handles,loc='lower center',bbox_to_anchor=(.53,.006),ncol=3,frameon=False,fontsize=10,columnspacing=1.1,handletextpad=.4)
    fig.subplots_adjust(left=.255,right=.98,top=.965,bottom=.12,hspace=.33)
    fig.savefig(ROOT/'Figure_4_4_Completed_Iteration_Delivery.png',dpi=300)
    fig.savefig(ROOT/'Figure_4_4_Completed_Iteration_Delivery.pdf')
    plt.close(fig)

if __name__=="__main__":
    p=argparse.ArgumentParser();p.add_argument("--carrier",required=True);p.add_argument("--out",required=True)
    a=p.parse_args();build(a.carrier,a.out)
